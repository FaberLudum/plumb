/// A declared public symbol: a function, struct, class, or const.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Symbol {
    /// The declaration keyword: "fn", "struct", "class", "def", "const", …
    pub kind: String,
    pub name: String,
}

pub const SCAN_MARKER: &str = "generated by `plumb index`";

/// Public symbols of one file, per the extension of `path`.
pub fn symbols(path: &str, text: &str) -> Vec<Symbol> {
    match extension(path).as_str() {
        "rs" => rust_symbols(text),
        "py" => python_symbols(text),
        "ts" | "tsx" | "js" | "jsx" | "mjs" | "cjs" => javascript_symbols(text),
        _ => Vec::new(),
    }
}

/// The full index document from (path, symbols) pairs. Sorts by path;
/// files with no symbols are omitted; always ends with a newline.
pub fn render(entries: &[(String, Vec<Symbol>)]) -> String {
    let mut sorted = entries.to_vec();
    sorted.sort_by(|a, b| a.0.cmp(&b.0));

    let mut doc = String::new();
    doc.push_str("# Index\n\n");
    doc.push_str("<!-- ");
    doc.push_str(SCAN_MARKER);
    doc.push_str("; do not edit by hand -->\n\n");
    doc.push_str("What this repository can already do, and where. Regenerate with\n");
    doc.push_str("`plumb index` after the public surface changes.\n");

    for (path, syms) in sorted {
        if syms.is_empty() {
            continue;
        }
        doc.push_str("\n## ");
        doc.push_str(&path);
        doc.push('\n');

        for symbol in syms {
            doc.push_str("- ");
            doc.push_str(&symbol.kind);
            doc.push_str(" `");
            doc.push_str(&symbol.name);
            doc.push_str("`\n");
        }
    }

    doc.push('\n');
    doc
}

/// Extract public symbols from Rust source code.
fn rust_symbols(text: &str) -> Vec<Symbol> {
    const RUST_KINDS: &[&str] = &[
        "fn", "struct", "enum", "trait", "const", "static", "mod", "type",
    ];

    let mut found = Vec::new();
    for line in text.lines() {
        if let Some(symbol) = rust_symbol(line, RUST_KINDS) {
            found.push(symbol);
        }
    }
    found
}

/// Match a single line for a Rust public symbol.
fn rust_symbol(line: &str, kinds: &[&str]) -> Option<Symbol> {
    let rest = line.trim_start().strip_prefix("pub ")?;
    // `pub(crate)`/`pub(super)` never reach here: their prefix is `pub(`,
    // not `pub `, so the strip above already rejected them.
    let (kind, rest) = kinds.iter().find_map(|kind| {
        rest.strip_prefix(kind)
            .filter(|tail| tail.starts_with(|c: char| c.is_whitespace()))
            .map(|tail| (*kind, tail))
    })?;
    let name = identifier(rest.trim_start());
    (!name.is_empty()).then(|| Symbol {
        kind: kind.to_string(),
        name,
    })
}

/// Extract public symbols from Python source code.
fn python_symbols(text: &str) -> Vec<Symbol> {
    let mut found = Vec::new();
    for line in text.lines() {
        // Skip empty lines
        if line.is_empty() {
            continue;
        }

        // Only top-level definitions (no leading whitespace)
        let first_char = match line.chars().next() {
            Some(c) => c,
            None => continue,
        };

        if first_char.is_whitespace() {
            // This line is indented; skip it completely
            continue;
        }

        // Try to match "def NAME"
        if let Some(rest) = line.strip_prefix("def ") {
            if let Some(n) = extract_python_name(rest).filter(|name| !name.starts_with('_')) {
                found.push(Symbol {
                    kind: "def".to_string(),
                    name: n,
                });
            }
        } else if let Some(rest) = line.strip_prefix("class ") {
            // Try to match "class NAME"
            if let Some(n) = extract_python_name(rest).filter(|name| !name.starts_with('_')) {
                found.push(Symbol {
                    kind: "class".to_string(),
                    name: n,
                });
            }
        }
    }
    found
}

/// Extract the name from a Python def/class line: stops at `(` for def, or at whitespace/`:` for class.
fn extract_python_name(text: &str) -> Option<String> {
    let name = text
        .chars()
        .take_while(|c| c.is_alphanumeric() || *c == '_')
        .collect::<String>();
    if name.is_empty() { None } else { Some(name) }
}

/// Extract public symbols from JavaScript/TypeScript source code.
fn javascript_symbols(text: &str) -> Vec<Symbol> {
    let mut found = Vec::new();
    for line in text.lines() {
        if let Some(symbol) = javascript_symbol(line) {
            found.push(symbol);
        }
    }
    found
}

/// Match a single line for a JavaScript/TypeScript export.
fn javascript_symbol(line: &str) -> Option<Symbol> {
    let trimmed = line.trim_start();

    // export function NAME, export async function NAME
    if let Some(rest) = trimmed.strip_prefix("export async function ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "function".to_string(),
                name,
            });
        }
    }

    if let Some(rest) = trimmed.strip_prefix("export function ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "function".to_string(),
                name,
            });
        }
    }

    // export default function NAME
    if let Some(rest) = trimmed.strip_prefix("export default function ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "function".to_string(),
                name,
            });
        }
    }

    // export class NAME
    if let Some(rest) = trimmed.strip_prefix("export class ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "class".to_string(),
                name,
            });
        }
    }

    // export const NAME
    if let Some(rest) = trimmed.strip_prefix("export const ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "const".to_string(),
                name,
            });
        }
    }

    // export let NAME
    if let Some(rest) = trimmed.strip_prefix("export let ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "let".to_string(),
                name,
            });
        }
    }

    // export interface NAME
    if let Some(rest) = trimmed.strip_prefix("export interface ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "interface".to_string(),
                name,
            });
        }
    }

    // export type NAME
    if let Some(rest) = trimmed.strip_prefix("export type ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "type".to_string(),
                name,
            });
        }
    }

    // export enum NAME
    if let Some(rest) = trimmed.strip_prefix("export enum ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "enum".to_string(),
                name,
            });
        }
    }

    None
}

/// Extract an identifier from the start of a string.
fn identifier(text: &str) -> String {
    text.chars()
        .take_while(|c| c.is_alphanumeric() || *c == '_')
        .collect()
}

/// The lowercased extension of `path`'s final path segment, or empty when it
/// has none.
fn extension(path: &str) -> String {
    let name = path.rsplit('/').next().unwrap_or(path);
    match name.rsplit_once('.') {
        Some((_, ext)) if !ext.is_empty() => ext.to_lowercase(),
        _ => String::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rust_public_items_are_extracted_with_their_kind() {
        let text = "\
pub fn run(repo: &Path) -> Result<()> {\n\
pub struct Outcome {\n\
pub(crate) fn hidden() {}\n\
fn private() {}\n\
    pub fn method(&self) {}\n\
pub const MARKER: &str = \"x\";\n";
        let found = symbols("crates/x/src/lib.rs", text);
        let pairs: Vec<(&str, &str)> = found
            .iter()
            .map(|symbol| (symbol.kind.as_str(), symbol.name.as_str()))
            .collect();
        assert_eq!(
            pairs,
            vec![
                ("fn", "run"),
                ("struct", "Outcome"),
                ("fn", "method"),
                ("const", "MARKER"),
            ]
        );
    }

    #[test]
    fn python_top_level_public_defs_and_classes_only() {
        let text = "def visible(x):\nclass Widget:\ndef _private():\n    def nested():\n";
        let found = symbols("api/app.py", text);
        let names: Vec<&str> = found.iter().map(|symbol| symbol.name.as_str()).collect();
        assert_eq!(names, vec!["visible", "Widget"]);
    }

    #[test]
    fn javascript_exported_declarations_are_extracted() {
        let text = "\
export function start() {}\n\
export async function stop() {}\n\
export const LIMIT = 3;\n\
export default function main() {}\n\
export { rename } from './other';\n\
const internal = 1;\n";
        let found = symbols("web/index.ts", text);
        let names: Vec<&str> = found.iter().map(|symbol| symbol.name.as_str()).collect();
        assert_eq!(names, vec!["start", "stop", "LIMIT", "main"]);
    }

    #[test]
    fn an_unknown_extension_yields_no_symbols() {
        assert!(symbols("README.md", "pub fn x() {}\n").is_empty());
    }

    #[test]
    fn render_is_sorted_deterministic_and_carries_the_marker() {
        let entries = vec![
            (
                "b.rs".to_string(),
                vec![Symbol {
                    kind: "fn".to_string(),
                    name: "beta".to_string(),
                }],
            ),
            (
                "a.rs".to_string(),
                vec![Symbol {
                    kind: "struct".to_string(),
                    name: "Alpha".to_string(),
                }],
            ),
            ("empty.rs".to_string(), vec![]),
        ];
        let document = render(&entries);
        assert!(document.contains(SCAN_MARKER), "{document}");
        let a = document.find("## a.rs").unwrap_or(usize::MAX);
        let b = document.find("## b.rs").unwrap_or(usize::MAX);
        assert!(a < b, "entries are not sorted by path:\n{document}");
        assert!(!document.contains("empty.rs"), "{document}");
        assert!(document.contains("- struct `Alpha`"), "{document}");
        assert!(document.contains("- fn `beta`"), "{document}");
        assert!(document.ends_with('\n'));
        assert_eq!(document, render(&entries), "render is not deterministic");
    }
}
