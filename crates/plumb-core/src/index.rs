/// A declared public symbol: a function, struct, class, or const.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Symbol {
    /// The declaration keyword: "fn", "struct", "class", "def", "const", …
    pub kind: String,
    pub name: String,
}

pub const SCAN_MARKER: &str = "generated by `plumb index`";

/// Public symbols of one file, per the extension of `path`.
pub fn symbols(path: &str, text: &str) -> Vec<Symbol> {
    match extension(path).as_str() {
        "rs" => rust_symbols(text),
        "py" => python_symbols(text),
        "ts" | "tsx" | "js" | "jsx" | "mjs" | "cjs" => javascript_symbols(text),
        _ => Vec::new(),
    }
}

/// Whether `path` is worth reading at all for the index scan: a known
/// source extension.
///
/// Path-only — no `text` parameter — on purpose, the same shape as
/// `boundaries::is_scannable`: [`symbols`] already returns an empty `Vec`
/// for an unrecognised extension without opening the file, so a caller that
/// knows the extension in advance can skip `std::fs::read` entirely for a
/// path this predicate rejects — see `plumb-cli`'s `scan_entries`, which
/// calls this before reading so a lockfile, an image, or any other tracked
/// binary in the repository is never read into memory for a scan whose
/// answer was always going to be "no symbols".
pub fn has_scannable_extension(path: &str) -> bool {
    is_known_extension(&extension(path))
}

/// Whether `extension` (already lowercased by [`extension`]) is one
/// [`symbols`] does anything with.
///
/// This list must be kept identical to the extensions matched in
/// [`symbols`]'s dispatch. The two are not merged into one because
/// [`symbols`] needs `text` to decide *which* extractor to run, while
/// [`has_scannable_extension`] must answer with no `text` at all — but a
/// language added to one list and not the other silently reopens the gap
/// [`has_scannable_extension`] exists to close:
/// `every_known_extension_is_dispatched_by_symbols` pins that they stay in
/// step.
fn is_known_extension(extension: &str) -> bool {
    matches!(
        extension,
        "rs" | "py" | "ts" | "tsx" | "js" | "jsx" | "mjs" | "cjs"
    )
}

/// The full index document from (path, symbols) pairs. Sorts by path;
/// files with no symbols are omitted; always ends with a newline.
pub fn render(entries: &[(String, Vec<Symbol>)]) -> String {
    let mut sorted = entries.to_vec();
    sorted.sort_by(|a, b| a.0.cmp(&b.0));

    let mut doc = String::new();
    doc.push_str("# Index\n\n");
    doc.push_str("<!-- ");
    doc.push_str(SCAN_MARKER);
    doc.push_str("; do not edit by hand -->\n\n");
    doc.push_str("What this repository can already do, and where. Regenerate with\n");
    doc.push_str("`plumb index` after the public surface changes.\n");

    for (path, syms) in sorted {
        if syms.is_empty() {
            continue;
        }
        doc.push_str("\n## ");
        doc.push_str(&path);
        doc.push('\n');

        for symbol in syms {
            doc.push_str("- ");
            doc.push_str(&symbol.kind);
            doc.push_str(" `");
            doc.push_str(&symbol.name);
            doc.push_str("`\n");
        }
    }

    doc.push('\n');
    doc
}

/// Extract public symbols from Rust source code.
fn rust_symbols(text: &str) -> Vec<Symbol> {
    const RUST_KINDS: &[&str] = &[
        "fn", "struct", "enum", "trait", "const", "static", "mod", "type",
    ];

    let mut found = Vec::new();
    for line in text.lines() {
        if let Some(symbol) = rust_symbol(line, RUST_KINDS) {
            found.push(symbol);
        }
    }
    found
}

/// Match a single line for a Rust public symbol.
fn rust_symbol(line: &str, kinds: &[&str]) -> Option<Symbol> {
    let rest = line.trim_start().strip_prefix("pub ")?;
    // `pub(crate)`/`pub(super)` never reach here: their prefix is `pub(`,
    // not `pub `, so the strip above already rejected them.
    let rest = strip_modifiers(rest);
    let (kind, rest) = kinds.iter().find_map(|kind| {
        rest.strip_prefix(kind)
            .filter(|tail| tail.starts_with(|c: char| c.is_whitespace()))
            .map(|tail| (*kind, tail))
    })?;
    let name = identifier(rest.trim_start());
    (!name.is_empty()).then(|| Symbol {
        kind: kind.to_string(),
        name,
    })
}

/// Peels `const`/`async`/`unsafe` modifiers off the front of `rest` (what
/// follows `pub `) so the kind match below sees the keyword actually being
/// declared.
///
/// `async ` and `unsafe ` are always modifiers — neither names a kind in
/// [`rust_symbols`]'s `RUST_KINDS` — so they are peeled unconditionally.
/// `const ` is ambiguous: `pub const fn new` has `const` modifying `fn`, but
/// `pub const MARKER: &str` has `const` *as* the kind. It is peeled only
/// when doing so still leaves a keyword behind — `fn`, or another modifier
/// that itself leads to one, as in `pub const unsafe fn x` — so a plain
/// `const`/`static` declaration is left untouched for the kind match to
/// claim.
fn strip_modifiers(mut rest: &str) -> &str {
    loop {
        if let Some(tail) = rest.strip_prefix("async ") {
            rest = tail;
        } else if let Some(tail) = rest.strip_prefix("unsafe ") {
            rest = tail;
        } else if let Some(tail) = rest
            .strip_prefix("const ")
            .filter(|tail| starts_with_modifiable_keyword(tail))
        {
            rest = tail;
        } else {
            break;
        }
    }
    rest
}

/// Whether `text` opens with `fn`, `async` or `unsafe` followed by
/// whitespace — the keywords a peeled `const ` may legally have been
/// modifying.
fn starts_with_modifiable_keyword(text: &str) -> bool {
    ["fn ", "async ", "unsafe "]
        .iter()
        .any(|keyword| text.starts_with(keyword))
}

/// Extract public symbols from Python source code.
fn python_symbols(text: &str) -> Vec<Symbol> {
    let mut found = Vec::new();
    for line in text.lines() {
        // Skip empty lines
        if line.is_empty() {
            continue;
        }

        // Only top-level definitions (no leading whitespace)
        let first_char = match line.chars().next() {
            Some(c) => c,
            None => continue,
        };

        if first_char.is_whitespace() {
            // This line is indented; skip it completely
            continue;
        }

        // Try to match "def NAME" or "async def NAME" — `async` stripped
        // first so the kind stays `def` either way.
        if let Some(rest) = line
            .strip_prefix("async ")
            .unwrap_or(line)
            .strip_prefix("def ")
        {
            if let Some(n) = extract_python_name(rest).filter(|name| !name.starts_with('_')) {
                found.push(Symbol {
                    kind: "def".to_string(),
                    name: n,
                });
            }
        } else if let Some(rest) = line.strip_prefix("class ") {
            // Try to match "class NAME"
            if let Some(n) = extract_python_name(rest).filter(|name| !name.starts_with('_')) {
                found.push(Symbol {
                    kind: "class".to_string(),
                    name: n,
                });
            }
        }
    }
    found
}

/// Extract the name from a Python def/class line: stops at `(` for def, or at whitespace/`:` for class.
fn extract_python_name(text: &str) -> Option<String> {
    let name = text
        .chars()
        .take_while(|c| c.is_alphanumeric() || *c == '_')
        .collect::<String>();
    if name.is_empty() { None } else { Some(name) }
}

/// Extract public symbols from JavaScript/TypeScript source code.
fn javascript_symbols(text: &str) -> Vec<Symbol> {
    let mut found = Vec::new();
    for line in text.lines() {
        if let Some(symbol) = javascript_symbol(line) {
            found.push(symbol);
        }
    }
    found
}

/// Match a single line for a JavaScript/TypeScript export.
fn javascript_symbol(line: &str) -> Option<Symbol> {
    let trimmed = line.trim_start();

    // export function NAME, export async function NAME
    if let Some(rest) = trimmed.strip_prefix("export async function ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "function".to_string(),
                name,
            });
        }
    }

    if let Some(rest) = trimmed.strip_prefix("export function ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "function".to_string(),
                name,
            });
        }
    }

    // export default function NAME, export default async function NAME
    if let Some(rest) = trimmed.strip_prefix("export default async function ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "function".to_string(),
                name,
            });
        }
    }

    if let Some(rest) = trimmed.strip_prefix("export default function ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "function".to_string(),
                name,
            });
        }
    }

    // export class NAME
    if let Some(rest) = trimmed.strip_prefix("export class ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "class".to_string(),
                name,
            });
        }
    }

    // export const NAME
    if let Some(rest) = trimmed.strip_prefix("export const ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "const".to_string(),
                name,
            });
        }
    }

    // export let NAME
    if let Some(rest) = trimmed.strip_prefix("export let ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "let".to_string(),
                name,
            });
        }
    }

    // export interface NAME
    if let Some(rest) = trimmed.strip_prefix("export interface ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "interface".to_string(),
                name,
            });
        }
    }

    // export type NAME
    if let Some(rest) = trimmed.strip_prefix("export type ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "type".to_string(),
                name,
            });
        }
    }

    // export enum NAME
    if let Some(rest) = trimmed.strip_prefix("export enum ") {
        let name = identifier(rest);
        if !name.is_empty() {
            return Some(Symbol {
                kind: "enum".to_string(),
                name,
            });
        }
    }

    None
}

/// Extract an identifier from the start of a string.
fn identifier(text: &str) -> String {
    text.chars()
        .take_while(|c| c.is_alphanumeric() || *c == '_')
        .collect()
}

/// The lowercased extension of `path`'s final path segment, or empty when it
/// has none.
fn extension(path: &str) -> String {
    let name = path.rsplit('/').next().unwrap_or(path);
    match name.rsplit_once('.') {
        Some((_, ext)) if !ext.is_empty() => ext.to_lowercase(),
        _ => String::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rust_public_items_are_extracted_with_their_kind() {
        let text = "\
pub fn run(repo: &Path) -> Result<()> {\n\
pub struct Outcome {\n\
pub(crate) fn hidden() {}\n\
fn private() {}\n\
    pub fn method(&self) {}\n\
pub const MARKER: &str = \"x\";\n";
        let found = symbols("crates/x/src/lib.rs", text);
        let pairs: Vec<(&str, &str)> = found
            .iter()
            .map(|symbol| (symbol.kind.as_str(), symbol.name.as_str()))
            .collect();
        assert_eq!(
            pairs,
            vec![
                ("fn", "run"),
                ("struct", "Outcome"),
                ("fn", "method"),
                ("const", "MARKER"),
            ]
        );
    }

    /// `const`, `async` and `unsafe` modifiers on `fn` must not shift the
    /// extracted kind or name: `pub const fn new` is kind `fn` name `new`,
    /// not kind `const` name `fn` — the fabricated entry a naive keyword
    /// match used to produce.
    #[test]
    fn rust_modifier_keywords_on_fn_are_not_mistaken_for_the_kind() {
        let text = "\
pub const fn new(x: i32) -> Self {\n\
pub async fn go() {\n\
pub unsafe fn raw() {\n\
pub const unsafe fn x() {\n";
        let found = symbols("crates/x/src/lib.rs", text);
        let pairs: Vec<(&str, &str)> = found
            .iter()
            .map(|symbol| (symbol.kind.as_str(), symbol.name.as_str()))
            .collect();
        assert_eq!(
            pairs,
            vec![("fn", "new"), ("fn", "go"), ("fn", "raw"), ("fn", "x")]
        );
    }

    /// A plain `const`/`static` declaration — no `fn` following — is still
    /// its own kind: `const` here is what is being declared, not a modifier
    /// on something else.
    #[test]
    fn rust_plain_const_and_static_are_unaffected_by_modifier_stripping() {
        let text = "pub const MARKER: &str = \"x\";\npub static X: i32 = 1;\n";
        let found = symbols("crates/x/src/lib.rs", text);
        let pairs: Vec<(&str, &str)> = found
            .iter()
            .map(|symbol| (symbol.kind.as_str(), symbol.name.as_str()))
            .collect();
        assert_eq!(pairs, vec![("const", "MARKER"), ("static", "X")]);
    }

    #[test]
    fn python_top_level_public_defs_and_classes_only() {
        let text = "def visible(x):\nclass Widget:\ndef _private():\n    def nested():\n";
        let found = symbols("api/app.py", text);
        let names: Vec<&str> = found.iter().map(|symbol| symbol.name.as_str()).collect();
        assert_eq!(names, vec!["visible", "Widget"]);
    }

    /// `async def` at top level must be extracted the same as `def`, kind
    /// `def`, and the leading-underscore exclusion still applies to it.
    #[test]
    fn python_async_def_is_extracted_as_kind_def() {
        let text = "async def fetch():\ndef sync_fetch():\nasync def _async_helper():\n";
        let found = symbols("api/app.py", text);
        let pairs: Vec<(&str, &str)> = found
            .iter()
            .map(|symbol| (symbol.kind.as_str(), symbol.name.as_str()))
            .collect();
        assert_eq!(pairs, vec![("def", "fetch"), ("def", "sync_fetch")]);
    }

    #[test]
    fn javascript_exported_declarations_are_extracted() {
        let text = "\
export function start() {}\n\
export async function stop() {}\n\
export const LIMIT = 3;\n\
export default function main() {}\n\
export default async function mainAsync() {}\n\
export { rename } from './other';\n\
const internal = 1;\n";
        let found = symbols("web/index.ts", text);
        let names: Vec<&str> = found.iter().map(|symbol| symbol.name.as_str()).collect();
        assert_eq!(names, vec!["start", "stop", "LIMIT", "main", "mainAsync"]);
    }

    #[test]
    fn an_unknown_extension_yields_no_symbols() {
        assert!(symbols("README.md", "pub fn x() {}\n").is_empty());
    }

    /// The path-only filter `symbols` implicitly applies via its extension
    /// dispatch, exposed so a caller (`plumb-cli`'s `scan_entries`) can skip
    /// `std::fs::read` entirely for a path `symbols` could never extract
    /// anything from — a lockfile, an image, any tracked binary.
    #[test]
    fn has_scannable_extension_matches_a_known_source_extension() {
        assert!(has_scannable_extension("crates/x/src/lib.rs"));
        assert!(!has_scannable_extension("Cargo.lock"));
        assert!(!has_scannable_extension("assets/logo.png"));
        assert!(!has_scannable_extension("tools/README"));
    }

    /// `has_scannable_extension`'s extension list and `symbols`'s dispatch
    /// must name the same languages, the same shape as
    /// `boundaries::every_known_extension_is_dispatched_by_imports`: a
    /// language added to one list and not the other silently reopens the gap
    /// `has_scannable_extension` exists to close.
    #[test]
    fn every_known_extension_is_dispatched_by_symbols() {
        let cases: &[(&str, &str)] = &[
            ("rs", "pub fn x() {}\n"),
            ("py", "def x():\n"),
            ("ts", "export function x() {}\n"),
            ("tsx", "export function x() {}\n"),
            ("js", "export function x() {}\n"),
            ("jsx", "export function x() {}\n"),
            ("mjs", "export function x() {}\n"),
            ("cjs", "export function x() {}\n"),
        ];
        for (ext, text) in cases {
            let path = format!("file.{ext}");
            assert!(
                has_scannable_extension(&path),
                "{ext} is dispatched by symbols but not recognised by has_scannable_extension"
            );
            assert!(
                !symbols(&path, text).is_empty(),
                "{ext} is recognised by has_scannable_extension but symbols() extracted nothing for it"
            );
        }
    }

    #[test]
    fn render_is_sorted_deterministic_and_carries_the_marker() {
        let entries = vec![
            (
                "b.rs".to_string(),
                vec![Symbol {
                    kind: "fn".to_string(),
                    name: "beta".to_string(),
                }],
            ),
            (
                "a.rs".to_string(),
                vec![Symbol {
                    kind: "struct".to_string(),
                    name: "Alpha".to_string(),
                }],
            ),
            ("empty.rs".to_string(), vec![]),
        ];
        let document = render(&entries);
        assert!(document.contains(SCAN_MARKER), "{document}");
        let a = document.find("## a.rs").unwrap_or(usize::MAX);
        let b = document.find("## b.rs").unwrap_or(usize::MAX);
        assert!(a < b, "entries are not sorted by path:\n{document}");
        assert!(!document.contains("empty.rs"), "{document}");
        assert!(document.contains("- struct `Alpha`"), "{document}");
        assert!(document.contains("- fn `beta`"), "{document}");
        assert!(document.ends_with('\n'));
        assert_eq!(document, render(&entries), "render is not deterministic");
    }
}
